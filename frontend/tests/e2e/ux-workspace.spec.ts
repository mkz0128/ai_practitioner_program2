test('地圖疊放對話後，仍可拖曳訂單跨車試算', async ({ page }) => {
  test.setTimeout(240_000)
  const consoleErrors: string[] = []
  const forbiddenRequests: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  page.on('request', (request) => { const url = request.url(); if (url.includes('googleapis') || url.endsWith('/dispatch')) forbiddenRequests.push(url) })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByLabel('上傳 Excel').setInputFiles(workbook)
  await page.getByRole('button', { name: '送出', exact: true }).click()
  await expect(page.locator('.topbar-stats')).toContainText('49/50', { timeout: 240_000 })
  const board = page.getByRole('list', { name: '四台車訂單看板' })
  const target = page.getByRole('region', { name: 'VEH-004 訂單欄' }).locator('.order-board-stop').nth(4)
  await board.locator('[data-order-id="ORD-042"]').dragTo(target)
  await expect(page.getByLabel('跨車站序預覽結果')).toBeVisible({ timeout: 30_000 })
  await page.screenshot({ path: path.join(shots, 'UX3-06-drag-preview.png') })
  await page.getByLabel('跨車站序預覽結果').getByRole('button', { name: '套用變更' }).click()
  await expect(page.getByRole('region', { name: 'VEH-004 訂單欄' }).locator('[data-order-id="ORD-042"]')).toHaveClass(/order-board-stop-changed/, { timeout: 60_000 })
  await expect(page.locator('.map-change-summary')).toContainText('ORD-042')
  await expect(page.locator('.map-stop-changed')).toHaveCount(1)
  await page.locator('.stage-map').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(shots, 'UX3-07-map-change-summary.png') })
  await page.getByRole('button', { name: '查看變更' }).click()
  await expect(page.getByRole('region', { name: 'VEH-004 訂單欄' }).locator('[data-order-id="ORD-042"]')).toBeInViewport({ ratio: 0.5 })
  await page.screenshot({ path: path.join(shots, 'UX3-07-cross-vehicle-highlight.png') })
  expect(consoleErrors).toEqual([])
  expect(forbiddenRequests).toEqual([])
})
